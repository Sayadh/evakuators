        յուրաքանչյուր բրաուզերի համար ստեղծվում է պատահական նույնացուցիչ, որը պահվում է cookie-ում
        (անվանում՝ <code>ev_visitor_id</code>, ժամկետը՝ մոտ 2 տարի) և բրաուզերի localStorage-ում։
        Այս նույնացուցիչը ինքնին <strong>չի պարունակում</strong> Ձեր IP հասցեն կամ որևէ այլ
        բացահայտող տվյալ. այն մեր տվյալների բազայում պահվում է միայն գաղտնի բանալիով հեշավորված
        տեսքով և օգտագործվում է բացառապես համախմբված (ագրեգացված) վիճակագրության ու
        չարաշահումների կանխարգելման համար, առանց իմանալու, թե ով է կոնկրետ մարդը։ Այս
        վիճակագրական գրառումները ավտոմատ կերպով ջնջվում են 180 օր հետո. միայն ընդհանրացված թվերը
        (օր.՝ ընդհանուր դիտումների քանակը) կարող են պահվել առանց ժամկետի, քանի որ դրանք այլևս
        կապված չեն կոնկրետ այցելուի հետ։
      </p>
      <p>
        Բացի սեփական վիճակագրությունից, հանրային կայքում (բացառությամբ ադմինիստրատիվ բաժնի)
        օգտագործվում են երրորդ կողմի վեբ վիճակագրության և գովազդի արդյունավետության հետագծման
        ծառայություններ։ Այս ծառայությունները տեղադրում են իրենց սեփական cookie-ները Ձեր
        բրաուզերում և իրենց մատակարարներին (ԱՄՆ) են փոխանցում այցելության տվյալները (դիտված էջեր,
        բրաուզերի/սարքի ընդհանուր տեսակ, մոտավոր աշխարհագրական դիրք)՝ նրանց սեփական գաղտնիության
        քաղաքականության և միջազգային տվյալների փոխանցման պայմանագրերի հիման վրա։
      </p>
      <p>
        Եթե Դուք թույլատրում եք բրաուզերին տրամադրել Ձեր տեղադրությունը «Մոտակա էվակուատոր»
        որոնման համար, այդ կոորդինատները մեր տվյալների բազայում չեն պահվում. դրանք ժամանակավորապես
        (առավելագույնը 5 րոպե) պահվում են սերվերի հիշողությունում՝ կլորացված ~110 մետր ճշտությամբ,
        կրկնվող որոնումները արագացնելու համար, և ինքնաբերաբար ջնջվում են ժամկետի ավարտից կամ
        սերվերի վերագործարկումից հետո։ Հեռավորությունը ճշգրիտ հաշվարկելու համար այդ կոորդինատները
        կարող են ուղարկվել արտաքին երթուղային ծառայությանը (տես 6-րդ կետը)։
      </p>

      <h2>6. Ո՞ւմ ենք փոխանցում տվյալները</h2>
      <p>
        Մենք չենք վաճառում Ձեր տվյալները և չենք փոխանցում դրանք երրորդ անձանց գովազդային նպատակներով
        (բացառությամբ 5-րդ կետում նկարագրված վիճակագրության և գովազդի հետագծման ծառայությունների)։
        Տվյալները հասանելի են՝
      </p>
      <ul>
        <li>կայքի բոլոր այցելուներին՝ միայն 2.1 կետում թվարկված հրապարակվող տվյալների մասով,</li>
        <li>
          ամպային պահեստավորման ծառայության մատակարարին՝ մեքենաների լուսանկարները պահպանելու
          համար,
        </li>
        <li>
          5-րդ կետում նշված վեբ վիճակագրության և գովազդի հետագծման մատակարարներին (ԱՄՆ),
        </li>
        <li>
          <strong>Telegram</strong>-ին՝ ադմինիստրատորներին և վարորդներին մուտքի կոդերի, ժամանակավոր
          գաղտնաբառերի և հայտերի մասին ծանուցումներ ուղարկելու համար,
        </li>
        <li>
          արտաքին երթուղագծման ծառայության մատակարարին (Գերմանիա)՝ մոտակա էվակուատորի ուղու
          հեռավորությունը հաշվարկելու համար,
        </li>
        <li>իրավապահ մարմիններին՝ միայն օրենքով նախատեսված դեպքերում և կարգով։</li>
      </ul>
      <p>
        Վերոնշյալ մատակարարներից մի քանիսը գործում են Հայաստանի Հանրապետության սահմաններից դուրս,
        հետևաբար Ձեր որոշ տվյալներ կարող են մշակվել կամ պահվել այլ պետությունում՝ այդ մատակարարների
        սեփական անվտանգության և տվյալների պաշտպանության երաշխիքների շրջանակում։ Հարթակի հիմնական
        սերվերի աշխարհագրական տեղակայման վերաբերյալ հստակեցումը՝
        <span
          >Հայաստան</span
        >։
      </p>

      <h2>7. Որքա՞ն ժամանակ ենք պահում</h2>
      <p>
        Ձեր պրոֆիլի տվյալները պահվում են այնքան ժամանակ, քանի դեռ Ձեր էջը հրապարակված է հարթակում։
        Երբ Դուք հետ եք կանչում Ձեր համաձայնությունը, Ձեր անձնական էջի կառավարումն անմիջապես
        արգելափակվում է, մինչև կրկին հաստատեք համաձայնությունը։ Հենց Ձեր էջի հրապարակումը
        փաստացիորեն դադարեցնելը (կայքի այցելուներից թաքցնելը) ներկայումս իրականացվում է հարթակի
        ադմինիստրացիայի կողմից՝ Ձեր պահանջով, այլ ոչ թե ինքնաշխատ, անմիջապես համաձայնության հետ
        կանչման պահին. սա մեր հայտնի սահմանափակումն է, որի ինքնաշխատացումն ընթացիկ
        առաջընթացի փուլում է։ Հիմքում ընկած տվյալների փաստացի, ամբողջական ջնջումն իրականացվում է
        Ձեր հստակ պահանջով՝ ողջամիտ ժամկետում, բացառությամբ այն դեպքերի, երբ դրանց պահպանումը
        պարտադիր է օրենքով։
      </p>
      <p>
        Այցելուների վիճակագրության հեշավորված նույնացուցիչները ջնջվում են ավտոմատ կերպով՝ 180 օր
        հետո։ Ձեր համաձայնության գրառումն ու դրա հետ կապված IP-ի հեշավորված նույնացուցիչը, Ձեր
        համաձայնությունը հետ կանչելուց կամ Ձեր էջը ջնջվելուց հետո, ավտոմատ կերպով ջնջվում են
        առավելագույնը 3 տարի հետո։
      </p>

      <h2>8. Ձեր իրավունքները</h2>
      <p>Դուք ցանկացած ժամանակ իրավունք ունեք՝</p>
      <ul>
        <li>իմանալ, թե Ձեր որ տվյալներն ենք մշակում,</li>
        <li>պահանջել ուղղել սխալ կամ ոչ ամբողջական տվյալները,</li>
        <li>պահանջել հեռացնել Ձեր տվյալները,</li>
        <li>դադարեցնել Ձեր էջի հրապարակումը,</li>
        <li>հետ կանչել Ձեր համաձայնությունը։</li>
      </ul>
      <p>
        Տվյալների մեծ մասը կարող եք ուղղել ինքնուրույն՝ Ձեր անձնական էջից։ Համաձայնությունը հետ
        կանչելը նշանակում է, որ Ձեր էջը այլևս չի կարող կառավարվել Ձեր կողմից, քանի որ հրապարակումն
        ու դրա կառավարումը հիմնված են հենց այդ համաձայնության վրա. Ձեր հստակ պահանջով
        ադմինիստրացիան այնուհետև դադարեցնում է նաև էջի փաստացի հրապարակումը (տես 7-րդ կետը)։
        Համաձայնության հետ կանչը հետադարձ ուժ չունի՝ այն չի ազդում մինչ այդ իրականացված մշակման
        օրինականության վրա։
      </p>

      <h2>9. Տեղադրության տվյալներ</h2>
      <p>
        Ձեր (վարորդի) հիմնական գտնվելու վայրի ճշգրիտ կոորդինատները, եթե Դուք դրանք տրամադրել եք,
        պահվում են մեր տվյալների բազայում և հասանելի են միայն Ձեզ՝ Ձեր անձնական էջից, և հարթակի
        ադմինիստրացիային՝ Ձեր հայտը հաստատելիս և մոդերացիայի ընթացքում։ Կայքի այցելուներին դրանք
        երբեք ուղղակիորեն չեն փոխանցվում. այցելուն տեսնում է միայն հաշվարկված հեռավորությունը և Ձեր
        նշած բնակավայրի անվանումը։
      </p>
      <p>
        Երբ կայքի այցելուն օգտագործում է «Մոտակա էվակուատոր» որոնումը, նրա բրաուզերի տված
        կոորդինատները չեն պահվում մեր տվյալների բազայում. դրանք օգտագործվում են միայն տվյալ
        որոնման ընթացքում (տես 5-րդ կետը)։ Ուղու հեռավորությունը հնարավորինս ճշգրիտ հաշվարկելու
        համար ինչպես այցելուի մոտավոր դիրքը, այնպես էլ մոտակա վարորդների կոորդինատները կարող են
        ուղարկվել արտաքին երթուղագծման ծառայությանը։
      </p>

      <h2>10. Անվտանգություն</h2>
      <p>Հարթակում կիրառվում են հետևյալ տեխնիկական և կազմակերպչական միջոցները՝</p>
      <ul>
        <li>Կապն ապահովված է HTTPS ծածկագրմամբ,</li>
        <li>Գաղտնաբառերը պահվում են միակողմանի հեշավորված տեսքով (bcrypt),</li>
